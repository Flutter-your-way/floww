  static List<CalSession> sessionsOf(CalLevel level) => switch (level) {
    CalLevel.one => levelOne,
    CalLevel.two => levelTwo,
    CalLevel.three => levelThree,
    CalLevel.four => levelFour,
  };

  static List<CalWeek> weeksOf(CalLevel level) => switch (level) {
    CalLevel.one => levelOneWeeks,
    CalLevel.two => levelTwoWeeks,
    CalLevel.three => levelThreeWeeks,
    CalLevel.four => levelFourWeeks,
  };

  static CalWeek weekOf(CalLevel level, int week) {
    final weeks = weeksOf(level);
    return weeks[(week - 1).clamp(0, weeks.length - 1)];
  }

